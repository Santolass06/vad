#!/usr/bin/env python3
"""Generates THIRD_PARTY_NOTICES.md from Cargo.lock (via `cargo metadata`), not by hand.

    scripts/gen_third_party_notices.py            # (re)write THIRD_PARTY_NOTICES.md
    scripts/gen_third_party_notices.py --check    # exit 1 if the file is stale vs Cargo.lock

Covers the Linux dependency graph of the workspace (the only supported target). License
texts are read from the crate sources in the cargo registry, so `cargo fetch` must have run.
Includes the font licenses that egui embeds in the binary (`epaint_default_fonts`).
This is a development tool; it is not a dependency of the product. It produces evidence of
notice obligations, not legal advice (see docs/legal/COMPONENTES.md and Sprint_17).
"""
import glob
import hashlib
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "THIRD_PARTY_NOTICES.md")
TARGET = "x86_64-unknown-linux-gnu"
LICENSE_GLOBS = ["LICENSE*", "LICENCE*", "COPYING*", "UNLICENSE*", "NOTICE*", "licenses/*", "LICENSES/*"]
EXTRA_GLOBS = {  # crates that embed assets with their own license files
    "epaint_default_fonts": ["fonts/*.txt"],
}


def metadata():
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--filter-platform", TARGET, "--locked"],
        cwd=ROOT, check=True, capture_output=True, text=True,
    ).stdout
    return json.loads(out)


def license_files(pkg):
    d = os.path.dirname(pkg["manifest_path"])
    patterns = LICENSE_GLOBS + EXTRA_GLOBS.get(pkg["name"], [])
    found = []
    for pat in patterns:
        for f in sorted(glob.glob(os.path.join(d, pat))):
            if os.path.isfile(f) and f not in found:
                found.append(f)
    return found


def generate():
    m = metadata()
    ws = set(m["workspace_members"])
    pkgs = sorted((p for p in m["packages"] if p["id"] not in ws), key=lambda p: (p["name"], p["version"]))
    lock = open(os.path.join(ROOT, "Cargo.lock"), "rb").read()
    texts = {}      # sha256 -> (text, [crate ids])
    entries = []
    missing = []
    for p in pkgs:
        files = license_files(p)
        hashes = []
        for f in files:
            raw = open(f, "rb").read().decode("utf-8", "replace").replace("\r\n", "\n").strip()
            h = hashlib.sha256(raw.encode()).hexdigest()
            texts.setdefault(h, (raw, []))[1].append(f"{p['name']} {p['version']}")
            hashes.append(h)
        if not files:
            missing.append(f"{p['name']} {p['version']}")
        entries.append((p, hashes))
    lines = [
        "# Third-party notices",
        "",
        "> Generated by `scripts/gen_third_party_notices.py` from `Cargo.lock`. **Do not edit by hand.**",
        "> Not legal advice: it is the notice evidence for Sprint_17 (see `docs/legal/COMPONENTES.md`).",
        "",
        f"Cargo.lock sha256: `{hashlib.sha256(lock).hexdigest()}`",
        f"Target: `{TARGET}` — {len(pkgs)} third-party crates",
        "",
        "Includes the font licenses of the fonts embedded in the binary by egui "
        "(`epaint_default_fonts`: Hack, Ubuntu-Light, Noto Emoji, emoji-icon-font).",
        "",
        "## Crates",
        "",
        "| Crate | Version | License (SPDX) | Source |",
        "| :--- | :--- | :--- | :--- |",
    ]
    for p, _ in entries:
        lines.append(f"| {p['name']} | {p['version']} | {p.get('license') or 'see license file'} | {p.get('repository') or ''} |")
    lines += ["", "## License texts", "",
              "Each distinct text appears once, followed by the crates whose source ships it.", ""]
    for i, (h, (text, who)) in enumerate(sorted(texts.items(), key=lambda kv: kv[1][1][0]), 1):
        lines += [f"### Text {i}", "", "Shipped by: " + ", ".join(sorted(set(who))), "", "```text", text, "```", ""]
    if missing:
        lines += ["## Crates without a license file in their source", "",
                  "The SPDX expression above is the only license information shipped by these crates; "
                  "the standard license text must be obtained from the SPDX list.", ""]
        lines += [f"- {c}" for c in missing]
        lines.append("")
    return "\n".join(lines)


def main():
    content = generate()
    if "--check" in sys.argv:
        current = open(OUT).read() if os.path.exists(OUT) else ""
        if current != content:
            print("THIRD_PARTY_NOTICES.md is stale vs Cargo.lock: run scripts/gen_third_party_notices.py", file=sys.stderr)
            return 1
        print("THIRD_PARTY_NOTICES.md is up to date")
        return 0
    open(OUT, "w").write(content)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
